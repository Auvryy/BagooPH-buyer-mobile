import 'package:bagoo_buyer_mobile/features/auth/google_identity.dart';

/// Only public values may be passed to Flutter's bundled Dart definitions.
class BuyerBuildConfiguration {
  BuyerBuildConfiguration._(this.origin, this.google);

  factory BuyerBuildConfiguration.parse(
    Object? value, {
    required String platform,
    required bool release,
  }) {
    const keys = {
      'BAGOO_BASE_URL',
      'BAGOO_GOOGLE_ENABLED',
      'BAGOO_GOOGLE_SERVER_CLIENT_ID',
      'BAGOO_GOOGLE_IOS_CLIENT_ID',
    };
    if (value is! Map<String, dynamic> ||
        value.keys.any((key) => !keys.contains(key))) {
      throw const FormatException(
        'Use only the public keys in config/buyer.example.json.',
      );
    }
    if (!['android', 'ios', 'linux'].contains(platform)) {
      throw const FormatException('Platform must be android, ios or linux.');
    }
    final base = value['BAGOO_BASE_URL'];
    final origin = base is String ? Uri.tryParse(base) : null;
    if (origin == null ||
        !['http', 'https'].contains(origin.scheme) ||
        origin.host.isEmpty ||
        !RegExp(r'^[A-Za-z0-9.:-]+$').hasMatch(origin.host) ||
        origin.userInfo.isNotEmpty ||
        !['', '/'].contains(origin.path) ||
        origin.hasQuery ||
        origin.hasFragment) {
      throw const FormatException(
        'BAGOO_BASE_URL must be an HTTP(S) origin without credentials or a path.',
      );
    }
    if (release &&
        (origin.scheme != 'https' ||
            origin.port != 443 ||
            _placeholder(origin.host) ||
            !RegExp(r'^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$')
                .hasMatch(origin.host))) {
      throw const FormatException(
        'Release requires the approved HTTPS buyer hostname on port 443.',
      );
    }
    final enabled = value['BAGOO_GOOGLE_ENABLED'] ?? false;
    final server = value['BAGOO_GOOGLE_SERVER_CLIENT_ID'] ?? '';
    final ios = value['BAGOO_GOOGLE_IOS_CLIENT_ID'] ?? '';
    if (enabled is! bool ||
        server is! String ||
        ios is! String ||
        server.isNotEmpty && !BuyerGoogleConfiguration.validClientId(server) ||
        ios.isNotEmpty && !BuyerGoogleConfiguration.validClientId(ios)) {
      throw const FormatException(
        'Use a boolean Google switch and public OAuth client IDs only.',
      );
    }
    final google = BuyerGoogleConfiguration(
      enabled: enabled,
      serverClientId: server,
      iosClientId: ios,
    );
    if (enabled &&
        (!BuyerGoogleConfiguration.validClientId(server) ||
            platform == 'ios' &&
                !BuyerGoogleConfiguration.validClientId(ios))) {
      throw const FormatException(
        'Google requires the Web/server client ID, plus the iOS client ID for iOS.',
      );
    }
    return BuyerBuildConfiguration._(origin, google);
  }

  final Uri origin;
  final BuyerGoogleConfiguration google;
  String get linkHost => origin.host;
  String get iosSettings =>
      '// Generated by tool/buyer.dart from public owner configuration.\n'
      'BAGOO_LINK_HOST = $linkHost\n'
      'BAGOO_GOOGLE_REVERSED_CLIENT_ID = ${google.enabled && google.iosClientId.isNotEmpty ? google.iosClientId.split('.').reversed.join('.') : 'invalid.bagoo.google-disabled'}\n';

  static bool _placeholder(String host) =>
      host == 'localhost' ||
      host.endsWith('.localhost') ||
      host.endsWith('.invalid') ||
      host.endsWith('.test') ||
      host == 'example.com' ||
      host.endsWith('.example.com') ||
      host == 'example.org' ||
      host.endsWith('.example.org') ||
      host == 'example.net' ||
      host.endsWith('.example.net');
}
